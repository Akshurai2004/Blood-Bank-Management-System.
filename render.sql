-- PostgreSQL schema and seed data for Render PostgreSQL.

CREATE TABLE IF NOT EXISTS hospital (
    hospitalid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospitalname VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(100) NOT NULL,
    contactno VARCHAR(15) NOT NULL,
    email VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS bloodbank (
    bloodbankid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bloodbankname VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(100) NOT NULL,
    contactno VARCHAR(15) NOT NULL,
    capacity INTEGER DEFAULT 1000
);

CREATE TABLE IF NOT EXISTS donor (
    donorid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donorname VARCHAR(100) NOT NULL,
    age INTEGER CHECK (age >= 18 AND age <= 65),
    gender VARCHAR(1) CHECK (gender IN ('M', 'F', 'O')),
    bloodgroup VARCHAR(5) NOT NULL,
    contactno VARCHAR(15) UNIQUE NOT NULL,
    email VARCHAR(100),
    address VARCHAR(255),
    lastdonationdate DATE,
    totaldonations INTEGER DEFAULT 0,
    registrationdate TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    isactive BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS bloodunit (
    unitid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donorid INTEGER NOT NULL REFERENCES donor(donorid) ON DELETE CASCADE,
    bloodbankid INTEGER NOT NULL REFERENCES bloodbank(bloodbankid) ON DELETE RESTRICT,
    bloodgroup VARCHAR(5) NOT NULL,
    quantity INTEGER DEFAULT 1 CHECK (quantity > 0),
    collectiondate DATE NOT NULL,
    expirationdate DATE NOT NULL CHECK (expirationdate > collectiondate),
    status VARCHAR(20) DEFAULT 'Available' CHECK (status IN ('Available', 'Reserved', 'Used', 'Expired')),
    component VARCHAR(30) DEFAULT 'Whole Blood' CHECK (component IN ('Whole Blood', 'RBC', 'Plasma', 'Platelets')),
    createdat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updatedat TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS patient (
    patientid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patientname VARCHAR(100) NOT NULL,
    age INTEGER CHECK (age > 0),
    gender VARCHAR(1) CHECK (gender IN ('M', 'F', 'O')),
    bloodgrouprequired VARCHAR(5) NOT NULL,
    hospitalid INTEGER NOT NULL REFERENCES hospital(hospitalid) ON DELETE CASCADE,
    contactno VARCHAR(15) NOT NULL,
    medicalcondition VARCHAR(255),
    registrationdate TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    isactive BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS request (
    requestid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patientid INTEGER NOT NULL REFERENCES patient(patientid) ON DELETE CASCADE,
    bloodbankid INTEGER NOT NULL REFERENCES bloodbank(bloodbankid) ON DELETE RESTRICT,
    requiredunits INTEGER DEFAULT 1 CHECK (requiredunits > 0),
    status VARCHAR(20) DEFAULT 'Pending' CHECK (status IN ('Pending', 'Fulfilled', 'Denied')),
    requestdate TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fulfilleddate TIMESTAMP
);

CREATE TABLE IF NOT EXISTS allocation (
    allocationid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requestid INTEGER NOT NULL REFERENCES request(requestid) ON DELETE CASCADE,
    unitid INTEGER NOT NULL REFERENCES bloodunit(unitid) ON DELETE RESTRICT,
    allocationdate TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    deliverystatus VARCHAR(20) DEFAULT 'Pending' CHECK (deliverystatus IN ('Pending', 'Delivered', 'Failed'))
);

CREATE TABLE IF NOT EXISTS app_user (
    userid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    passwordhash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'Donor' CHECK (role IN ('Donor', 'Hospital', 'Admin', 'SuperAdmin')),
    donorid INTEGER REFERENCES donor(donorid) ON DELETE SET NULL,
    hospitalid INTEGER REFERENCES hospital(hospitalid) ON DELETE SET NULL,
    bloodbankid INTEGER REFERENCES bloodbank(bloodbankid) ON DELETE SET NULL,
    createdat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updatedat TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_donor_bloodgroup ON donor (bloodgroup);
CREATE INDEX IF NOT EXISTS idx_bloodunit_status ON bloodunit (status);
CREATE INDEX IF NOT EXISTS idx_bloodunit_expiration ON bloodunit (expirationdate);
CREATE INDEX IF NOT EXISTS idx_request_status ON request (status);

CREATE OR REPLACE VIEW availablebloodinventory AS
SELECT bb.bloodbankid, bb.bloodbankname, bb.location, bu.bloodgroup,
       COUNT(*) AS totalunits, SUM(bu.quantity) AS totalquantity,
       MIN(bu.expirationdate) AS nearestexpiry,
       (MIN(bu.expirationdate) - CURRENT_DATE) AS daysuntilexpiry
FROM bloodunit bu
JOIN bloodbank bb ON bu.bloodbankid = bb.bloodbankid
WHERE bu.status = 'Available' AND bu.expirationdate > CURRENT_DATE
GROUP BY bb.bloodbankid, bb.bloodbankname, bb.location, bu.bloodgroup;

